#include <stdio.h>

int main(void)
{
  printf("10 - 4 * 2 + 18 / 4 %% 3 = %d\n", 10 - 4 * 2 + 18 / 4 % 3);
  printf("7 / 2 * 2 = %d\n", 7 / 2 * 2);
  printf("7 * 2 / 2 = %d\n", 7 * 2 / 2);
  printf("1 / 2 * 3.0 = %.1f\n", 1 / 2 * 3.0);
  printf("3.0 * 1 / 2 = %.1f\n", 3.0 * 1 / 2);
  printf("2 + 3 * 4 - 6 / 3 = %d\n", 2 + 3 * 4 - 6 / 3);

  return 0;
}
